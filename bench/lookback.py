"""
lookback.md -- a running log of every benchmark run: the command, what had
changed in the code before it, the score, and for every question the
question, gold SQL, our SQL and the result rows.

Rebuilt automatically at the end of every bench/run_benchmark.py run.
Rebuild by hand:   python bench/lookback.py
"""

import json
import subprocess
from datetime import datetime
from pathlib import Path

BENCH = Path(__file__).resolve().parent
ROOT = BENCH.parent
RESULTS = BENCH / "results"
LOOKBACK = BENCH / "lookback.md"
RUNS = RESULTS / "runs.json"     # results file name -> {command, note, commit}


def _runs() -> dict:
    return json.loads(RUNS.read_text()) if RUNS.exists() else {}


def _commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        return "?"


def record_run(results_file: Path, command: str, note: str | None = None) -> None:
    runs = _runs()
    entry = runs.get(results_file.name, {})
    entry.update(command=command, commit=_commit())
    if note:
        entry["note"] = note
    runs[results_file.name] = entry
    RESULTS.mkdir(exist_ok=True)
    RUNS.write_text(json.dumps(runs, indent=1))
    rebuild()


def _pretty(sql: str | None) -> str:
    if not sql:
        return "(none)"
    try:
        import sqlglot
        return sqlglot.transpile(sql, read="sqlite", write="sqlite", pretty=True)[0]
    except Exception:
        return " ".join(sql.split())


def _when(name: str) -> str:
    try:
        return datetime.strptime(name[10:25], "%Y%m%d_%H%M%S").strftime("%d %b %Y, %H:%M")
    except ValueError:
        return name


def _rows(rows, count) -> str:
    if rows is None:
        return "not recorded (run made before row logging)"
    shown = ", ".join(str(tuple(r)) for r in rows)
    more = f" … ({count} rows total)" if count and count > len(rows) else ""
    return f"{count} row(s): {shown}{more}" if count else "0 rows"


def _status(r: dict) -> str:
    if r.get("gold_error"):
        return "SKIP (gold SQL failed)"
    if r["ex_strict"]:
        return "PASS"
    if r["clarified"]:
        return "ASKED (best guess " + ("correct" if r["ex_guess"] else "wrong") + ")"
    return "FAIL" + (" (right logic, extra columns)" if r.get("ex_lenient") else "")


def _pct(a, b) -> str:
    return f"{100 * a / b:.0f}% ({a}/{b})" if b else "n/a"


def rebuild() -> Path:
    runs = _runs()
    files = sorted(RESULTS.glob("benchmark_*.jsonl"))
    parsed = []
    for f in files:
        results = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
        if results:
            parsed.append((f, results, runs.get(f.name, {})))

    out = ["# Lookback: benchmark runs", "",
           "Every run of `bench/run_benchmark.py`, oldest first: the command, what changed before it, "
           "the score, and each question's SQL and result. Generated by `bench/lookback.py`; "
           "per-question raw data is in `bench/results/benchmark_*.jsonl`.", "",
           "## Progress", "",
           "| Run | When | Command | Questions | EX strict | EX best guess | EX lenient | Asked | Avg latency |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for i, (f, rs, meta) in enumerate(parsed, 1):
        scored = [r for r in rs if not r.get("gold_error")]
        n = len(scored)
        cmd = meta.get("command", "not recorded").replace("python tests/run_benchmark.py ", "").replace("python bench/run_benchmark.py ", "").replace('"$BIRD_Q"', "…").replace('"$BIRD_DB"', "…")
        out.append(f"| [{i}](#run-{i}) | {_when(f.name)} | `{cmd}` | {len(rs)} | "
                   f"{_pct(sum(r['ex_strict'] for r in scored), n)} | {_pct(sum(r['ex_guess'] for r in scored), n)} | "
                   f"{_pct(sum(r.get('ex_lenient', r['ex_guess']) for r in scored), n)} | "
                   f"{_pct(sum(r['clarified'] for r in scored), n)} | "
                   f"{sum(r['latency_s'] for r in rs) / len(rs):.1f}s |")
    out.append("")

    for i, (f, rs, meta) in enumerate(parsed, 1):
        out += [f"## Run {i}", "",
                f"- **When:** {_when(f.name)}",
                f"- **Results file:** `bench/results/{f.name}`",
                f"- **Command:** `{meta.get('command', 'not recorded')}`"]
        if meta.get("commit"):
            out.append(f"- **Code version:** `{meta['commit']}`")
        if meta.get("note"):
            out.append(f"- **What changed before this run:** {meta['note']}")
        out.append("")
        for r in rs:
            out += [f"### Q{r['id']}: {_status(r)}", "",
                    f"*{r['db_id']}, {r['difficulty']}, confidence {r.get('confidence')}, "
                    f"{r.get('attempts')} attempt(s), {r['latency_s']}s*", "",
                    f"**Question:** {r['question']}", ""]
            if r.get("evidence"):
                out += [f"**Hint:** {r['evidence']}", ""]
            out += ["**Gold SQL**", "", "```sql", _pretty(r["gold_sql"]), "```", "",
                    "**Our SQL**", "", "```sql", _pretty(r.get("pred_sql")), "```", "",
                    f"- Our result: {_rows(r.get('pred_rows'), r.get('pred_row_count'))}",
                    f"- Gold result: {_rows(r.get('gold_rows'), r.get('gold_row_count'))}"]
            if r.get("pred_error"):
                out.append(f"- Error: `{r['pred_error']}`")
            for h in r.get("trace") or []:
                if (h.get("error") or "").startswith(("logic fix", "no such column")) or "repaired alias" in (h.get("error") or ""):
                    out.append(f"- Fix applied: {h['error']}")
            out.append("")
    LOOKBACK.write_text("\n".join(out))
    return LOOKBACK


if __name__ == "__main__":
    print(f"wrote {rebuild()}")
